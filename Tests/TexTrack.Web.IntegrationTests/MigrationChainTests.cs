    [Fact]
    public async Task Negative_stock_policy_migration_preserves_existing_stock_companies_and_blocks_empty_companies()
    {
        var sourceConnection = TestDatabaseSettings.GetConnectionString();
        var adminBuilder = new NpgsqlConnectionStringBuilder(sourceConnection) { SearchPath = string.Empty };
        var schema = $"negative_policy_migration_{Guid.NewGuid():N}";

        await using var admin = new NpgsqlConnection(adminBuilder.ConnectionString);
        await admin.OpenAsync();
        await using (var create = new NpgsqlCommand($"CREATE SCHEMA \"{schema}\"", admin))
            await create.ExecuteNonQueryAsync();

        try
        {
            var testBuilder = new NpgsqlConnectionStringBuilder(adminBuilder.ConnectionString) { SearchPath = schema };
            await using var connection = new NpgsqlConnection(testBuilder.ConnectionString);
            await connection.OpenAsync();
            await using (var fixture = new NpgsqlCommand("""
                CREATE TABLE companies
                (
                    id bigint PRIMARY KEY
                );
                CREATE TABLE stock_movements
                (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company_id bigint NOT NULL
                );
                CREATE TABLE audit_logs
                (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company_id bigint NOT NULL,
                    entity_type varchar(100) NOT NULL,
                    entity_id bigint,
                    action varchar(50) NOT NULL,
                    success boolean NOT NULL,
                    description varchar(1000) NOT NULL,
                    performed_by varchar(100) NOT NULL,
                    performed_at_utc timestamp with time zone NOT NULL
                );
                INSERT INTO companies(id) VALUES (1), (2);
                INSERT INTO stock_movements(company_id) VALUES (1);
                """, connection))
            {
                await fixture.ExecuteNonQueryAsync();
            }

            var migrationPath = Path.Combine(
                AppContext.BaseDirectory, "Data", "Migrations", "041_negative_stock_policy.sql");
            await using (var migrate = new NpgsqlCommand(await File.ReadAllTextAsync(migrationPath), connection))
                await migrate.ExecuteNonQueryAsync();

            await using var verify = new NpgsqlCommand("""
                SELECT
                    (SELECT allow_negative_stock FROM companies WHERE id = 1),
                    (SELECT allow_negative_stock FROM companies WHERE id = 2),
                    (SELECT COUNT(*) FROM audit_logs WHERE entity_type = 'CompanyInventoryPolicy'),
                    (SELECT COUNT(*) FROM audit_logs WHERE company_id = 1 AND description LIKE '%preserved Allow Negative Stock%'),
                    (SELECT COUNT(*) FROM audit_logs WHERE company_id = 2 AND description LIKE '%enabled Block Negative Stock%')
                """, connection);
            await using var reader = await verify.ExecuteReaderAsync();
            Assert.True(await reader.ReadAsync());
            Assert.True(reader.GetBoolean(0));
            Assert.False(reader.GetBoolean(1));
            Assert.Equal(2L, reader.GetInt64(2));
            Assert.Equal(1L, reader.GetInt64(3));
            Assert.Equal(1L, reader.GetInt64(4));
        }
        finally
        {
            await using var drop = new NpgsqlCommand($"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE", admin);
            await drop.ExecuteNonQueryAsync();
        }
    }

