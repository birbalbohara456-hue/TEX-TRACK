            foreach (var entityType in mappedDb.Model.GetEntityTypes())
            {
                var table = entityType.GetTableName();
                if (table is null || !criticalTables.Contains(table)) continue;
                var storeObject = StoreObjectIdentifier.Table(table, entityType.GetSchema());
                foreach (var property in entityType.GetProperties())
                {
                    var column = property.GetColumnName(storeObject);
                    if (column is null) continue;
                    Assert.True(databaseColumns.TryGetValue((table, column), out var nullable),
                        $"EF maps {table}.{column}, but the migration-built PostgreSQL schema does not contain it.");
                    Assert.Equal(property.IsNullable, nullable);
                }
            }
