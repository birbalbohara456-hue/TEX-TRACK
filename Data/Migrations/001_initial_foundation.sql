CREATE TABLE IF NOT EXISTS companies
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    name_normalized varchar(200) NOT NULL,
    code varchar(50) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at_utc timestamp with time zone NOT NULL,
    modified_at_utc timestamp with time zone NOT NULL,
    created_by varchar(100) NOT NULL,
    modified_by varchar(100) NOT NULL,
    concurrency_token varchar(32) NOT NULL,
    CONSTRAINT uq_companies_name_normalized UNIQUE (name_normalized),
    CONSTRAINT uq_companies_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS financial_years
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    name varchar(50) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at_utc timestamp with time zone NOT NULL,
    modified_at_utc timestamp with time zone NOT NULL,
    created_by varchar(100) NOT NULL,
    modified_by varchar(100) NOT NULL,
    concurrency_token varchar(32) NOT NULL,
    CONSTRAINT uq_financial_years_company_name UNIQUE (company_id, name)
);

CREATE TABLE IF NOT EXISTS ledger_groups
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    parent_id bigint NULL REFERENCES ledger_groups(id) ON DELETE RESTRICT,
    name varchar(200) NOT NULL,
    name_normalized varchar(200) NOT NULL,
    alias varchar(200) NOT NULL DEFAULT '',
    root_classification varchar(80) NOT NULL DEFAULT '',
    is_system boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at_utc timestamp with time zone NOT NULL,
    modified_at_utc timestamp with time zone NOT NULL,
    created_by varchar(100) NOT NULL,
    modified_by varchar(100) NOT NULL,
    concurrency_token varchar(32) NOT NULL,
    CONSTRAINT uq_ledger_groups_company_name UNIQUE (company_id, name_normalized)
);
CREATE INDEX IF NOT EXISTS ix_ledger_groups_parent ON ledger_groups(parent_id);

CREATE TABLE IF NOT EXISTS uqcs
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    name varchar(200) NOT NULL,
    name_normalized varchar(200) NOT NULL,
    alias varchar(200) NOT NULL DEFAULT '',
    short_name varchar(20) NOT NULL,
    decimal_places integer NOT NULL DEFAULT 0,
    is_system boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at_utc timestamp with time zone NOT NULL,
    modified_at_utc timestamp with time zone NOT NULL,
    created_by varchar(100) NOT NULL,
    modified_by varchar(100) NOT NULL,
