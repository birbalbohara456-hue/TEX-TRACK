    company_id bigint NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    name varchar(200) NOT NULL,
    name_normalized varchar(200) NOT NULL,
    alias varchar(200) NOT NULL DEFAULT '',
    system_type_code varchar(60) NOT NULL,
    nature varchar(100) NOT NULL,
    posting_mode varchar(100) NOT NULL,
    abbreviation varchar(20) NOT NULL DEFAULT '',
    allow_manual_numbering boolean NOT NULL DEFAULT false,
    prefix varchar(30) NOT NULL DEFAULT '',
    starting_number integer NOT NULL DEFAULT 1,
    tally_voucher_type_name varchar(200) NOT NULL DEFAULT '',
    is_system boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_at_utc timestamp with time zone NOT NULL,
    modified_at_utc timestamp with time zone NOT NULL,
    created_by varchar(100) NOT NULL,
    modified_by varchar(100) NOT NULL,
    concurrency_token varchar(32) NOT NULL,
    CONSTRAINT uq_voucher_types_company_name UNIQUE (company_id, name_normalized),
    CONSTRAINT uq_voucher_types_company_system_code UNIQUE (company_id, system_type_code)
);

CREATE TABLE IF NOT EXISTS audit_logs
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NULL,
    entity_type varchar(100) NOT NULL,
    entity_id bigint NULL,
    action varchar(50) NOT NULL,
    success boolean NOT NULL,
    description varchar(1000) NOT NULL,
    performed_by varchar(100) NOT NULL,
    performed_at_utc timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_audit_logs_company_time ON audit_logs(company_id, performed_at_utc);

